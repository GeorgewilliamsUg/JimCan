class TestUserManagementGuardrails(BasePhase5TestCase):
    """Validates last active Owner protection, step-up auth, and session revocation."""

    def test_cannot_deactivate_last_active_owner(self):
        """When only 1 active Owner remains, deactivating that Owner is rejected."""
        # Deactivate Owner 2 so only Owner 1 is active
        self.owner2_user.is_active = False
        self.owner2_user.save()

        client = self._get_client_for_role('Owner')
        resp = client.post(reverse('accounts:user_toggle_active', kwargs={'user_id': self.owner_user.pk}))
        self.assertEqual(resp.status_code, 302)

        self.owner_user.refresh_from_db()
        self.assertTrue(self.owner_user.is_active, "Last active Owner must not be deactivated!")

    def test_cannot_demote_last_active_owner(self):
        """Demoting the last active Owner fails form validation and role is preserved."""
        self.owner2_user.is_active = False
        self.owner2_user.save()

        client = self._get_client_for_role('Owner')
        resp = client.post(
            reverse('accounts:user_edit', kwargs={'user_id': self.owner_user.pk}),
            {
                'first_name': self.owner_user.first_name,
                'last_name': self.owner_user.last_name,
                'email': self.owner_user.email,
                'role': ROLE_FINANCE,
            }
        )
        self.assertEqual(resp.status_code, 200)
        self.assertIn("Cannot demote the last active Owner account.", resp.content.decode('utf-8'))

        self.owner_user.refresh_from_db()
        self.assertEqual(get_user_role(self.owner_user), ROLE_OWNER)

    def test_deactivation_ends_secondary_sessions(self):
        """Deactivating an account calls sign_out_everywhere."""
        client = self._get_client_for_role('Owner')
        with patch('accounts.user_views.sign_out_everywhere') as mock_signout:
            resp = client.post(reverse('accounts:user_toggle_active', kwargs={'user_id': self.staff_user.pk}))
            self.assertEqual(resp.status_code, 302)
            mock_signout.assert_called_once_with(self.staff_user)

    def test_role_change_ends_secondary_sessions(self):
        """Changing a user's role calls sign_out_everywhere."""
        client = self._get_client_for_role('Owner')
        with patch('accounts.user_views.sign_out_everywhere') as mock_signout:
            resp = client.post(
                reverse('accounts:user_edit', kwargs={'user_id': self.staff_user.pk}),
                {
                    'first_name': 'Sam',
                    'last_name': 'Staff',
                    'email': 'staff@jimcan.site',
                    'role': ROLE_FINANCE,
                }
            )
            self.assertEqual(resp.status_code, 302)
            mock_signout.assert_called_once_with(self.staff_user)

    def test_user_creation_requires_step_up_reauth(self):
        """Owner without recent reauth is redirected to step-up reauth screen."""
        client = Client()
        client.force_login(self.owner_user)
        # Clear reauth_at
        session = client.session
        session.pop('reauth_at', None)
        session.save()

        resp = client.get(reverse('accounts:user_create'))
        self.assertEqual(resp.status_code, 302)
        self.assertIn(reverse('accounts:reauth'), resp.url)

    def test_permission_denied_logs_to_security_noise(self):
        """Permission denied 403 events are captured in SecurityNoise table."""
        initial_noise = SecurityNoise.objects.filter(event_type='permission_denied_403').count()
        client = self._get_client_for_role('Site staff')
        client.get(reverse('dashboard:invoices'))

        new_noise = SecurityNoise.objects.filter(event_type='permission_denied_403').count()
        self.assertGreater(new_noise, initial_noise)


